// Regenerate resident dialogs and their runtime index from the asset pack translations.
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const languagePath = path.join(root, "ModdCorp Asset Pack", "assets", "dialog", "lang", "en_us.json");
const outputDir = path.join(root, "ModdCorp Data Pack", "data", "dialog", "dialogs");
const indexPath = path.join(root, "kubejs", "server_scripts", "moddcorp", "townsfolkDialogData.js");
const language = JSON.parse(fs.readFileSync(languagePath, "utf8").replace(/^\uFEFF/, ""));
const chatter = {};

for (const key of Object.keys(language)) {
    const match = /^dialog\.npc\.(townsfolk_[a-z0-9_]+|cityfolk(?:_child)?|tourist(?:_child)?)\.dialog\.chatter_(\d+)\.line_(\d+)$/.exec(key);
    if (!match) continue;
    const [, family, variation, line] = match;
    if (!chatter[family]) chatter[family] = {};
    if (!chatter[family][variation]) chatter[family][variation] = {};
    chatter[family][variation][line] = key;
}

const towns = Object.keys(language)
    .map(key => /^dialog\.npc\.townsfolk_([a-z0-9_]+)\.name$/.exec(key))
    .filter(match => match && chatter[`townsfolk_${match[1]}`])
    .map(match => match[1]).sort();
const index = {};
const skins = [];

function addFamily(idFamily, sourceFamily, speaker, skipEmpty) {
    const variations = chatter[sourceFamily];
    if (!variations || !language[speaker]) {
        throw new Error(`Missing chatter or speaker translation for ${idFamily}: ${sourceFamily}, ${speaker}`);
    }
    index[idFamily] = [];
    for (const variation of Object.keys(variations).map(Number).sort((a, b) => a - b)) {
        const lines = variations[variation];
        const lineNumbers = Object.keys(lines).map(Number).sort((a, b) => a - b);
        if (lineNumbers.some((number, i) => number !== i)) {
            throw new Error(`Non-contiguous lines in ${sourceFamily} chatter_${variation}`);
        }
        if (skipEmpty && lineNumbers.some(line => !language[lines[line]].trim())) continue;
        const id = `moddcorp_resident_${idFamily}_chatter_${variation}`;
        const entries = lineNumbers.map((line, i) => ({
            id: i === 0 ? "start" : `line_${line}`,
            speaker: { translate: speaker, color: "white" },
            text: [{ translate: lines[line] }],
            ...(i === lineNumbers.length - 1 ? { endDialog: true } : {})
        }));
        const dialog = { id, title: id, description: lines[0], entries };
        fs.writeFileSync(path.join(outputDir, `${id}.json`), JSON.stringify(dialog, null, "\t") + "\n");
        index[idFamily].push(id);
    }
}

if (!towns.length) throw new Error("No townsfolk translations found.");
for (const town of towns) {
    for (const suffix of ["", "_child"]) {
        const speaker = `dialog.npc.townsfolk_${town}.name`;
        addFamily(`townsfolk_${town}${suffix}`, `townsfolk_${town}${suffix}`, speaker);
        addFamily(`tourist_${town}${suffix}`, `tourist${suffix}`, speaker);
        addFamily(`generic_townsfolk_${town}${suffix}`, `townsfolk_generic${suffix}`, speaker, true);
        addFamily(`generic_tourist_${town}${suffix}`, `townsfolk_generic${suffix}`, speaker, true);
        for (const [gender, model] of [["male", "humanoid"], ["female", "humanoid_slim"]]) {
            const filename = `${town}_${gender}${suffix}.png`;
            if (fs.existsSync(path.join(root, "config", "easy_npc", "skin", model, filename))) {
                skins.push(`${model}/${filename}`);
            }
        }
    }
}
for (const suffix of ["", "_child"]) {
    addFamily(`cityfolk${suffix}`, `cityfolk${suffix}`, "dialog.npc.cityfolk_chesno.name");
    addFamily(`generic_cityfolk${suffix}`, `townsfolk_generic${suffix}`, "dialog.npc.cityfolk_chesno.name", true);
}
fs.writeFileSync(indexPath, `// Generated by tools/generate_townsfolk_dialogs.js. Do not edit by hand.\nglobal.townsfolkDialogs = ${JSON.stringify(index, null, 2)};\nglobal.townsfolkSkins = ${JSON.stringify(skins, null, 2)};\n`);
console.log(`Generated ${Object.values(index).reduce((total, ids) => total + ids.length, 0)} resident dialogs for ${towns.length} towns.`);
